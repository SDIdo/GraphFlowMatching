#!/usr/bin/env python3
"""
Assemble the LaTeX report from the artefacts produced by training and
evaluation.

Reads
  * ``<eval_dir>/metrics.json``      written by evaluation/evaluate_gfm.py
  * ``<run_dir>/train_log_*.csv``    written by utils/loss_logger.py
  * ``<run_dir>/run_config.json``    written by train.py

Writes into ``paper/generated/``
  * ``results_table.tex``   FID / IS / MMD / KID per dataset
  * ``loss_table.tex``      final and best training loss, steps, wall-clock
  * ``config_table.tex``    the configuration each run was trained with
  * ``status.tex``          a banner naming which runs are still missing

and copies the t-SNE / sample-grid figures into ``paper/figures/``.

Every table renders with ``--`` placeholders for runs whose artefacts do not
exist yet, so ``paper/main.tex`` always compiles.

Example
-------
    python scripts/build_paper.py \
        --result CIFAR-10=results/cifar10 \
        --result ImageNet=results/imagenet \
        --result ImageNet-LT=results/imagenet_lt \
        --run CIFAR-10=runs/cifar10/models \
        --run ImageNet=runs/imagenet/models \
        --run ImageNet-LT=runs/imagenet_lt/models
"""

import argparse
import csv
import json
import os
import shutil

PAPER_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "paper")
PAPER_DIR = os.path.normpath(PAPER_DIR)
GEN_DIR = os.path.join(PAPER_DIR, "generated")
FIG_DIR = os.path.join(PAPER_DIR, "figures")

MISS = "--"


def tex_escape(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                 ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        s = str(s).replace(a, b)
    return s


def parse_pairs(specs):
    out = {}
    for spec in specs or []:
        label, _, path = spec.partition("=")
        if not path:
            label, path = os.path.basename(os.path.normpath(label)), label
        out[label] = path
    return out


def load_json(path):
    if path and os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return None


def read_csv_rows(path):
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def fmt(v, digits=2, missing=MISS):
    if v is None:
        return missing
    try:
        return f"{float(v):.{digits}f}"
    except (TypeError, ValueError):
        return missing


